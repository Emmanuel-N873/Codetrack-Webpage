const score = 70;




//conditional logic
if (score > 70) {
    console.log("Excellent");
} else if (score === 70) {
    console.log("Very Good");
} else {
    console.log("Try Again");
}


//SWITCH CASE
switch(score) {
    case 1:
        console.log("One");
        break;
    case 2:
        console.log("Two");
        break;
    case 3:
        console.log("Three");
        break;
    default:
        console.log("Invalid Number");
}
